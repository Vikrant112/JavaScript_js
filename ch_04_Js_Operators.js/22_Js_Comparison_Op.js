// Compoarison Operators in JavaScript
// ==, ===, !=, !==, >, <, >=, <=

// = - Assignment Operator

// == => loose comparison operator(Sikh vs hindu)
// === => strict comparison operator(sikh vs hindu, language and culture)

pizza == pizza;// only value
domino === pizzahut; // (type and content)

// > , <, >=, <= => comparison operators

console.log(10 > 5); // Output: true
console.log(10 < 5); // Output: false
console.log(10 >= 5); // Output: true
console.log(10 <= 5); // Output: false

console.log(5 =="5"); // Output: true
console.log(5 ==="5"); // Output: false

// != => not equal to
console.log(5 != 5); // value comaprison, Output: false
console.log(5 !== "5"); // value and type comparison, Output: true

console.log(5===5); // true
