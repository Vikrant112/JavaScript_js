// +, - , *, /, %, **
//Arithematic operators

let a = 10; 
let b = 3;

let sum = a + b; // addition
let sub = a - b; // subtraction
let mul = a * b; // multiplication
let div = a / b; // division

console.log("Sum: " + sum); // Output: Sum: 13
console.log("Subtraction: " + sub); // Output: Subtraction: 7
console.log("Multiplication: " + mul); // Output: Multiplication: 30
console.log("Division: " + div); // Output: Division: 3.3333333333333335

// Modulus -> % -> it will give you remainder
console.log("Modulus: " + (a % b)); // Output: Modulus: 1

console.log(13%7); // Output: 6

//n%2 == 0 -> even
//n%2 == 1 -> odd

// Exponentiation -> ** -> it will give you power, power 2^3 => 8
console.log("Exponentiation: " + (2 ** 3)); // Output: Exponentiation: 8
console.log("Exponentiation: " + (a ** b)); // Output: Exponentiation: 9